#Python - Sort Lists

#Sort List Alphanumerically
fruits = ["orange", "mango", "kiwi", "pineapple", "banana"]
fruits.sort()
# print(fruits)

thislist = [100, 50, 65, 82, 23]
thislist.sort()
# print(thislist)

# Sort Descending:
fruits = ["orange", "mango", "kiwi", "pineapple", "banana"]
fruits.sort(reverse=True)
# print(fruits)

thislist = [100, 50, 65, 82, 23]
thislist.sort(reverse = True)
print(thislist)